"""Pydantic schemas for conversations and pre-RAG questions."""

from datetime import datetime
from typing import List, Optional
from pydantic import BaseModel, ConfigDict, Field


class PolicyContextSummary(BaseModel):
    """Context of the currently resolved policy within a conversation."""

    model_config = ConfigDict(from_attributes=True)

    policy_id: str
    policy_number: str
    customer_id: str
    customer_name: str
    line_of_business: Optional[str] = None
    product_name: Optional[str] = None
    status: Optional[str] = None


class ConversationCreateRequest(BaseModel):
    """Request payload to initiate a new conversation session."""

    policy_id: Optional[str] = None


class ConversationContextUpdateRequest(BaseModel):
    """Request payload to set/update resolved policy context for a conversation."""

    policy_id: str = Field(..., min_length=1, description="Policy UUID to bind to context")
    customer_id: Optional[str] = Field(None, description="Expected customer/account UUID for relationship validation")
    confirm_different_customer: bool = Field(False, description="Explicit confirmation when switching to an unrelated customer")


class CustomerSummary(BaseModel):
    id: str
    name: str


class PolicySummary(BaseModel):
    id: str
    policy_number: str
    line_of_business: str
    product_name: str


class ContextCheckResponse(BaseModel):
    switch_type: str  # "same_customer_same_policy" | "same_customer_different_policy" | "different_customer" | "initial_selection"
    requires_confirmation: bool
    current_customer: Optional[CustomerSummary] = None
    current_policy: Optional[PolicySummary] = None
    target_customer: CustomerSummary
    target_policy: PolicySummary
    allowed: bool = True
    message: Optional[str] = None


class ContextSwitchAuditItem(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    conversation_id: str
    employee_id: str
    employee_name: Optional[str] = None
    employee_role: Optional[str] = None
    timestamp: datetime
    previous_customer_id: Optional[str] = None
    previous_customer_name: Optional[str] = None
    previous_policy_id: Optional[str] = None
    previous_policy_number: Optional[str] = None
    new_customer_id: Optional[str] = None
    new_customer_name: Optional[str] = None
    new_policy_id: Optional[str] = None
    new_policy_number: Optional[str] = None
    switch_type: str
    outcome: str
    reason: Optional[str] = None


class ConversationResponse(BaseModel):
    """Conversation session response with optional policy context."""

    model_config = ConfigDict(from_attributes=True)

    conversation_id: str
    employee_id: str
    status: str
    created_at: datetime
    updated_at: datetime
    policy_context: Optional[PolicyContextSummary] = None


class QuestionSubmitRequest(BaseModel):
    """Request payload for submitting a policy question."""

    question: str = Field(..., min_length=1, description="Question text submitted by employee")
    # Answer about this policy instead of the conversation's context, without changing the context.
    # Used when one question is answered for each of a customer's matching policies.
    policy_id: Optional[str] = None


class QuestionSubmitResponse(BaseModel):
    """Pre-RAG structured question response ready for evidence retrieval."""

    model_config = ConfigDict(from_attributes=True)

    conversation_id: str
    question: str
    policy_context: PolicyContextSummary
    timestamp: datetime
    status: str = "ready_for_retrieval"


class QuestionHistoryItem(BaseModel):
    """Historical question entry within a conversation."""

    model_config = ConfigDict(from_attributes=True)

    id: str
    conversation_id: str
    question: str
    policy_id: Optional[str] = None
    status: str
    created_at: datetime


class AskedBy(BaseModel):
    """Who asked a question. name and role are None when they were not recorded."""

    employee_id: str
    name: Optional[str] = None
    role: Optional[str] = None


class ConversationSummary(BaseModel):
    """One of the current employee's conversations, for the history list."""

    conversation_id: str
    # The first question, truncated; never generated by a model.
    title: str
    created_at: datetime
    last_activity_at: datetime
    question_count: int
    asked_by: AskedBy
    policy_number: Optional[str] = None
    customer_name: Optional[str] = None
    # Outcome of the latest answer: answered, needs_review, insufficient_evidence, or None if unanswered.
    latest_outcome: Optional[str] = None


class ConversationListPage(BaseModel):
    items: List[ConversationSummary]
    total: int
    limit: int
    offset: int


class ConversationArchiveResponse(BaseModel):
    conversation_id: str
    is_archived: bool
    archived_at: Optional[datetime] = None
